// Regenerates src/data/projects.js from the scraped thewebsitemakers.in data.
// Usage: node scripts/gen-projects.mjs [path/to/makers_projects.json]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const input = resolve(root, process.argv[2] ?? 'docs/makers_projects.json')
const output = resolve(root, 'src/data/projects.js')

const CATEGORIES = [
  'Clothing',
  'Shopify',
  'Jewellery',
  'Foods / Restaurants',
  'E-commerce / Accessories',
  'LMS / Education',
  'Travel / Bookings',
  'Hospitality',
  'Interiors / Construction',
  'Blogging / News',
  'Photography',
  'Imports / Exports',
  'Healthcare',
  'Nonprofits / NGOs',
  'Finance / Insurance',
  'Hiring Consultancy',
  'Custom Software Development',
  'Other Websites',
]

// Source-site slugs that use a different label from the portfolio's categories.
const ALIASES = {
  'other-startup-websites': 'Other Websites',
}

// One-line blurbs built only from name + category; no invented details.
const BLURBS = {
  Clothing: (n) => `Clothing and fashion website for ${n}.`,
  Shopify: (n) => `Shopify storefront for ${n}.`,
  Jewellery: (n) => `Jewellery showcase and store for ${n}.`,
  'Foods / Restaurants': (n) => `Food and restaurant website for ${n}.`,
  'E-commerce / Accessories': (n) => `E-commerce storefront for ${n}.`,
  'LMS / Education': (n) => `Education and learning website for ${n}.`,
  'Travel / Bookings': (n) => `Travel and bookings website for ${n}.`,
  Hospitality: (n) => `Hospitality website for ${n}.`,
  'Interiors / Construction': (n) => `Interiors and construction website for ${n}.`,
  'Blogging / News': (n) => `Blog and news website for ${n}.`,
  Photography: (n) => `Photography portfolio website for ${n}.`,
  'Imports / Exports': (n) => `Imports and exports business website for ${n}.`,
  Healthcare: (n) => `Healthcare website for ${n}.`,
  'Nonprofits / NGOs': (n) => `Nonprofit website for ${n}.`,
  'Finance / Insurance': (n) => `Finance and insurance website for ${n}.`,
  'Hiring Consultancy': (n) => `Hiring and recruitment consultancy website for ${n}.`,
  'Custom Software Development': (n) => `Custom software build for ${n}.`,
  'Other Websites': (n) => `Business website for ${n}.`,
}

const urlKey = (url) => url.trim().toLowerCase().replace(/\/+$/, '')

const data = JSON.parse(readFileSync(input, 'utf8'))
const seen = new Set()
const projects = []
let dropped = 0

for (const [rawKey, items] of Object.entries(data)) {
  const category = ALIASES[rawKey] ?? rawKey
  if (!CATEGORIES.includes(category)) {
    throw new Error(`Unknown category "${rawKey}" in ${input}`)
  }
  for (const item of items) {
    const name = item.name?.trim()
    const url = item.url?.trim()
    if (!name || !url) throw new Error(`Missing name/url in ${category}: ${JSON.stringify(item)}`)
    const key = urlKey(url)
    if (seen.has(key)) {
      dropped++
      continue
    }
    seen.add(key)
    projects.push({
      name,
      url,
      category,
      blurb: BLURBS[category](name),
      image: item.image?.trim() || null,
    })
  }
}

const source = `// Generated by scripts/gen-projects.mjs from docs/makers_projects.json. Do not edit by hand.
export const PROJECT_CATEGORIES = ${JSON.stringify(CATEGORIES, null, 2)}

export const PROJECTS = ${JSON.stringify(projects, null, 2)}
`

writeFileSync(output, source)
console.log(`Wrote ${projects.length} projects to ${output} (${dropped} duplicate URLs dropped)`)
